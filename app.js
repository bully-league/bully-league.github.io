function gameCard(g) {
  const isLink = Boolean(g.channelUrl);
  const card = el(isLink ? "a" : "div", "card" + (g.isGotw ? " gotw" : ""));
  if (isLink) { card.href = g.channelUrl; card.target = "_blank"; card.rel = "noopener"; }

  const away = team(g.awayTeamId), home = team(g.homeTeamId);

  if (g.isGotw) {
    const eyebrow = el("div", "gotw-eyebrow");
    eyebrow.appendChild(svgIcon("M12 2l2.4 4.9 5.4.8-3.9 3.8.9 5.4L12 14.3 7.2 16.9l.9-5.4L4.2 7.7l5.4-.8z"));
    eyebrow.appendChild(document.createTextNode("Game of the Week"));
    card.appendChild(eyebrow);

    const billboard = el("div", "gotw-billboard");
    billboard.style.setProperty("--bb-away", railColor(away.abbr));
    billboard.style.setProperty("--bb-home", railColor(home.abbr));
    billboard.appendChild(logoImg(away.abbr, "bb-logo"));
    billboard.appendChild(el("span", "gotw-vs", "VS"));
    billboard.appendChild(logoImg(home.abbr, "bb-logo"));
    card.appendChild(billboard);
  }
  const body = el("div", "game");
  body.style.setProperty("--rail", `linear-gradient(to bottom, ${railColor(away.abbr)} 0%, ${railColor(away.abbr)} 48%, ${railColor(home.abbr)} 52%, ${railColor(home.abbr)} 100%)`);

  const decidedByForce = g.forced === "forceWin";
  const awayWon = decidedByForce ? g.forcedWinnerTeamId === g.awayTeamId : g.played && g.awayScore > g.homeScore;
  const homeWon = decidedByForce ? g.forcedWinnerTeamId === g.homeTeamId : g.played && g.homeScore > g.awayScore;
  const decided = g.played || decidedByForce || g.forced === "fairSim";

  for (const [t, score, won] of [[away, g.awayScore, awayWon], [home, g.homeScore, homeWon]]) {
    const row = el("div", "game-row" + (decided && !won && (awayWon || homeWon) ? " loser" : ""));
    row.appendChild(logoImg(t.abbr));
    const name = el("div", "team-name");
    name.appendChild(el("span", "nick", t.nick));
    const rec = record(t.teamId);
    if (rec) name.appendChild(el("span", "record", rec));
    row.appendChild(name);
    row.appendChild(el("span", "score", g.played ? String(score) : "—"));
    if (won) row.appendChild(el("span", "winner-tick"));
    body.appendChild(row);
  }

  const meta = el("div", "game-meta");
  if (g.forced === "forceWin") meta.appendChild(el("span", "chip forced", "Force Win"));
  else if (g.forced === "fairSim") meta.appendChild(el("span", "chip fairsim", "Fair Sim"));
  else if (g.played) meta.appendChild(el("span", "chip final", "Final"));
  else meta.appendChild(el("span", "chip live", "Scheduled"));
  if (isLink) {
    const link = el("span", "discord-link");
    link.appendChild(svgIcon(DISCORD_PATH));
    link.appendChild(document.createTextNode("Game channel"));
    meta.appendChild(link);
  }
  body.appendChild(meta);
  card.appendChild(body);
  return card;
}

