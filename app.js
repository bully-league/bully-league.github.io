const RENDERERS = { home: renderHome, standings: renderStandings, rankings: renderRankings, leaders: renderLeaders, news: renderNews, trade: renderTrade };
let activeTab = "home";
let lastRenderedTab = null;

function render() {
  const view = document.getElementById("view");
  const keepScroll = lastRenderedTab === activeTab;
  const y = window.scrollY;
  view.replaceChildren();
  if (!DATA) { view.appendChild(el("div", "loading", "Loading league data…")); return; }
  RENDERERS[activeTab](view);
  lastRenderedTab = activeTab;
  // Re-rendering the SAME tab (the trade builder does this on every tap) keeps the
  // scroll position; switching tabs starts at the top like a page change should.
  window.scrollTo(0, keepScroll ? y : 0);
}

for (const btn of document.querySelectorAll(".tab")) {
  btn.addEventListener("click", () => {
    activeTab = btn.dataset.tab;
    for (const b of document.querySelectorAll(".tab")) {
      b.classList.toggle("active", b === btn);
      b.setAttribute("aria-selected", String(b === btn));
    }
    render();
  });
}

async function load() {
  try {
    const res = await fetch("site.json", { cache: "no-cache" });
    DATA = await res.json();
  } catch {
    // Offline / fetch failed — the SW may still have served a cached copy via the
    // fetch handler; if not, show the shell's empty state.
    if (!DATA) {
      document.getElementById("view").replaceChildren(el("div", "empty", "Can't reach the league right now — try again when you're back online."));
      return;
    }
  }
  teamIndex.clear();
  for (const t of DATA.teams || []) teamIndex.set(t.teamId, t);
  document.getElementById("week-chip").textContent = DATA.weekLabel || "—";
  render();
}

